import sharp from 'sharp'
import { mkdir, readdir, stat, writeFile } from 'node:fs/promises'

await mkdir('src/assets/responsive', { recursive: true })
const imports = []
const entries = []

for (const name of await readdir('src/assets')) {
  if (!name.endsWith('.png')) continue
  const source = `src/assets/${name}`
  const target = source.replace(/\.png$/, '.webp')
  const result = await sharp(source).webp({ lossless: true, effort: 6 }).toFile(target)
  console.log(`${name}: ${(await stat(source)).size} → ${result.size} bytes (WebP sem perda)`)
  const base = name.replace(/\.png$/, '')
  const key = base.replaceAll('-', '_')
  const { width } = await sharp(source).metadata()
  imports.push(`import ${key} from '../assets/${base}.webp'`)
  const candidates = []
  for (const size of [96, 160, 240, 320].filter((size) => size < width)) {
    const file = `${base}-${size}.webp`
    const variant = await sharp(source).resize({ width: size, withoutEnlargement: true }).webp({ lossless: true, effort: 6 }).toFile(`src/assets/responsive/${file}`)
    const variable = `${key}_${size}`
    imports.push(`import ${variable} from '../assets/responsive/${file}'`)
    candidates.push(`\${${variable}} ${size}w`)
    console.log(`  ${size}px: ${variant.size} bytes`)
  }
  candidates.push(`\${${key}} ${width}w`)
  entries.push(`  [${key}]: \`${candidates.join(', ')}\`,`)
}

await writeFile('src/lib/nft-images.generated.ts', `// Generated by npm run images:optimize. Keep original dimensions and aspect ratios.\n${imports.join('\n')}\n\nexport const nftImageSources: Record<string, string> = {\n${entries.join('\n')}\n}\n`)
