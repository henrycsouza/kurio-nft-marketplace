import { test, expect } from '@playwright/test'

test('componentes compartilhados salvam perfil e carteira; menu funciona pelo teclado', async ({ page }, testInfo) => {
  test.skip(!['mobile', 'desktop'].includes(testInfo.project.name), 'Fluxos principais em desktop e celular')
  await page.goto('/profile')
  await page.getByRole('button', { name: 'Entrar ou criar conta' }).click()
  const auth = page.getByRole('dialog')
  await auth.locator('input[name="email"]').fill('colecionador@kurio.test')
  await auth.locator('input[name="password"]').fill('Kurio123!')
  await auth.locator('button.auth-submit').click()
  await expect(page).toHaveURL(/\/profile$/)
  await expect(page.locator('input[name="name"]')).toHaveAttribute('data-slot', 'input')
  await page.locator('input[name="name"]').fill('Colecionador Teste')
  await expect(page.getByRole('button', { name: 'Salvar', exact: true })).toHaveAttribute('data-slot', 'button')
  await page.getByRole('button', { name: 'Salvar', exact: true }).click()
  await expect(page.getByText('Perfil atualizado com sucesso.')).toBeVisible()
  await page.reload()
  await expect(page.locator('input[name="name"]')).toHaveValue('Colecionador Teste')
  if (testInfo.project.name === 'desktop') {
    const trigger = page.getByRole('button', { name: 'Abrir menu de Colecionador Teste' })
    await trigger.focus()
    await page.keyboard.press('ArrowDown')
    const menu = page.getByRole('menu', { name: 'Menu da conta' })
    await expect(menu).toBeVisible()
    await expect(menu.getByRole('menuitem', { name: /Ver perfil/ })).toBeFocused()
    await page.keyboard.press('End')
    await expect(menu.getByRole('menuitem', { name: 'Sair', exact: true })).toBeFocused()
    await page.screenshot({ path: 'test-results/profile-menu-shadcn-desktop.png' })
    await page.keyboard.press('Escape')
    await expect(menu).toBeHidden()
    await expect(trigger).toBeFocused()
  }
  await page.goto('/wallets')
  await page.locator('.wallet-section').first().getByRole('button', { name: 'Editar', exact: true }).click()
  await page.locator('input[name="nickname"]').fill('Minha carteira atualizada')
  await page.getByRole('button', { name: 'Salvar carteira', exact: true }).click()
  await expect(page.getByText('Carteira salva. Ela já está disponível no pagamento.')).toBeVisible()
  await page.reload()
  await page.locator('.wallet-section').first().getByRole('button', { name: 'Editar', exact: true }).click()
  await expect(page.locator('input[name="nickname"]')).toHaveValue('Minha carteira atualizada')
})
