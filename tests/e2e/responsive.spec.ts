test('redimensionamento contínuo reorganiza a página sem recarregar', async ({ page }, testInfo) => {
  test.skip(testInfo.project.name !== 'desktop', 'Uma sessão desktop é redimensionada por todos os intervalos')
  await page.goto('/')
  await expect(page.locator('#catalogo .nft-card').first()).toBeVisible()
  for (const width of [1440, 1100, 1024, 1023, 900, 820, 768, 700, 600, 599, 430, 390, 360, 320]) {
    await page.setViewportSize({ width, height: 900 })
    await expect(page.locator('.mobile-bottom-nav')).toBeVisible({ visible: width < 1024 })
    await expect(page.locator('.catalog-sidebar')).toBeVisible({ visible: width >= 1024 })
    expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth), `Overflow em ${width}px`).toBeTruthy()
    const columns = await page.locator('#catalogo .catalog-grid').evaluate((element) => getComputedStyle(element).gridTemplateColumns.split(' ').length)
    expect(columns).toBe(width < 600 ? 2 : 3)
    if ([820, 600, 390].includes(width)) await page.screenshot({ path: `test-results/resized-${width}.png`, fullPage: false })
  }
  await page.getByRole('button', { name: 'Abrir filtros e ordenação' }).click()
  await expect(page.getByRole('dialog', { name: 'Filtros e ordenação' })).toBeVisible()
  await page.setViewportSize({ width: 1440, height: 1000 })
  await expect(page.getByRole('dialog', { name: 'Filtros e ordenação' })).toBeHidden()
  await expect(page.locator('.site-header')).toBeVisible()
})



