import { test, expect } from '@playwright/test'

test('layout do catálogo, navegação e ausência de overflow', async ({ page }, testInfo) => {
  await page.goto('/')
  await expect(page.locator('#catalogo .nft-card').first()).toBeVisible()
  await page.evaluate(() => document.fonts.ready)
  const mobile = page.viewportSize()!.width < 1024
  await expect(page.locator('.mobile-bottom-nav')).toBeVisible({ visible: mobile })
  const cards = page.locator('#catalogo .nft-card')
  const first = await cards.nth(0).boundingBox()
  const second = await cards.nth(1).boundingBox()
  expect(second!.x).toBeGreaterThan(first!.x + first!.width)
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBeTruthy()
  if (mobile) {
    await expect(page.locator('.mobile-hero')).toBeVisible()
    await expect(page.locator('.catalog-sidebar')).toBeHidden()
    await page.getByRole('button', { name: 'Mostrar destaque 2' }).click()
    await expect(page.getByRole('heading', { name: 'ARTE RARA, NOVAS HISTÓRIAS' })).toBeVisible()
    await page.getByRole('button', { name: 'Mostrar destaque 1' }).click()
  }
  await page.screenshot({ path: `test-results/home-${testInfo.project.name}-viewport.png`, fullPage: false })
  await page.screenshot({ path: `test-results/home-${testInfo.project.name}.png`, fullPage: true })
  expect(await page.locator('#catalogo .nft-card-badge').count()).toBeLessThanOrEqual(1)
})

test('filtros mobile abrem, filtram e preservam a URL ao recarregar', async ({ page }) => {
  test.skip(page.viewportSize()!.width >= 1024, 'Painel específico de telefone e tablet')
  await page.goto('/')
  await expect(page.locator('#catalogo .nft-card').first()).toBeVisible()
  await page.getByRole('button', { name: 'Abrir filtros e ordenação' }).click()
  const dialog = page.getByRole('dialog', { name: 'Filtros e ordenação' })
  await expect(dialog).toBeVisible()
  const filteredResponse = page.waitForResponse((response) => { const url = new URL(response.url()); return url.pathname === '/api/nfts' && [...url.searchParams.getAll('categories'), ...url.searchParams.getAll('categories[]')].includes('Arte digital') })
  await dialog.getByText('Arte digital', { exact: true }).click()
  const filtered = await (await filteredResponse).json()
  await dialog.getByRole('button', { name: /Ver.*resultados/ }).click()
  await expect(dialog).toBeHidden()
  await expect(page.locator('#catalogo .nft-card')).toHaveCount(filtered.items.length)
  await page.reload()
  await expect(page.locator('#catalogo .nft-card')).toHaveCount(filtered.items.length)
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBeTruthy()
})

