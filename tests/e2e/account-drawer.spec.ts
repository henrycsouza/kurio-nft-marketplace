import { test, expect } from '@playwright/test'

test('seta lateral abre as seções da conta, navega e fecha por Escape', async ({ page }, testInfo) => {
  test.skip(testInfo.project.name === 'desktop', 'Menu lateral de celular/tablet')
  await page.goto('/profile')
  await page.getByRole('button', { name: 'Entrar ou criar conta' }).click()
  const auth = page.getByRole('dialog')
  await auth.locator('input[name="email"]').fill('colecionador@kurio.test')
  await auth.locator('input[name="password"]').fill('Kurio123!')
  await auth.locator('button.auth-submit').click()
  await expect(page).toHaveURL(/\/profile$/)
  await expect(page.locator('#account-mobile-route')).toHaveCount(0)
  const trigger = page.getByRole('button', { name: 'Abrir navegação da conta' })
  await expect(trigger).toBeVisible()
  const bounds = await trigger.boundingBox()
  expect(bounds!.x).toBe(0)
  expect(Math.abs(bounds!.y + bounds!.height / 2 - page.viewportSize()!.height / 2)).toBeLessThan(2)
  await trigger.click()
  const drawer = page.getByRole('dialog', { name: 'Minha conta' })
  await expect(drawer).toBeVisible()
  await expect(drawer.getByRole('link', { name: 'Dados do perfil' })).toHaveAttribute('aria-current', 'page')
  await expect(drawer.getByRole('button', { name: 'Sair da conta' })).toBeVisible()
  await expect(drawer).toHaveCSS('opacity', '1')
  await page.screenshot({ path: `test-results/account-drawer-${testInfo.project.name}.png` })
  await drawer.getByRole('link', { name: 'Configurações' }).click()
  await expect(page).toHaveURL(/\/settings$/)
  await expect(drawer).toBeHidden()
  await expect(page.getByRole('switch', { name: /Reduzir animações/ })).toBeVisible()
  await page.getByRole('button', { name: 'Abrir navegação da conta' }).click()
  await page.keyboard.press('Escape')
  await expect(drawer).toBeHidden()
  await expect(page.getByRole('button', { name: 'Abrir navegação da conta' })).toBeFocused()
  await page.getByRole('button', { name: 'Abrir navegação da conta' }).click()
  await page.setViewportSize({ width: 1440, height: 1000 })
  await expect(drawer).toBeHidden()
  await expect(page.locator('.collector-sidebar')).toBeVisible()
  await expect(page.getByRole('button', { name: 'Abrir navegação da conta' })).toBeHidden()
})

test('banner do celular avança mesmo com mouse sobre ele e após tocar nas barras', async ({ page }, testInfo) => {
  test.skip(testInfo.project.name !== 'mobile', 'Gesto e emulação do celular')
  await page.clock.install()
  await page.goto('/')
  const hero = page.getByRole('region', { name: 'Destaques Kurio' })
  await expect(hero).toBeVisible()
  const bounds = await hero.boundingBox()
  await hero.getByRole('link', { name: /EXPLORAR/ }).focus()
  await page.mouse.move(bounds!.x + 20, bounds!.y + 20)
  await page.clock.fastForward(10100)
  await expect(hero.getByRole('button', { name: 'Mostrar destaque 2' })).toHaveAttribute('aria-pressed', 'true')
  await hero.getByRole('button', { name: 'Mostrar destaque 1' }).tap()
  await page.clock.fastForward(10100)
  await expect(hero.getByRole('button', { name: 'Mostrar destaque 2' })).toHaveAttribute('aria-pressed', 'true')
  await page.setViewportSize({ width: 768, height: 1024 })
  await expect(hero.locator('.mobile-hero-playback')).toHaveCount(0)
  await page.clock.fastForward(10100)
  await expect(hero.getByRole('button', { name: 'Mostrar destaque 3' })).toHaveAttribute('aria-pressed', 'true')
  await page.setViewportSize({ width: 1440, height: 1000 })
  await expect(hero).toBeHidden()
  await expect(page.locator('.desktop-hero')).toBeVisible()
  await page.clock.fastForward(25000)
  await expect(page.locator('.mobile-hero button[aria-label="Mostrar destaque 3"]')).toHaveAttribute('aria-pressed', 'true')
})


