import { test, expect } from '@playwright/test'

test('publicação serve assets e permite refresh e acesso direto', async ({ page, request }) => {
  const worker = await request.get('/mockServiceWorker.js')
  expect(worker.status()).toBe(200)
  expect(worker.headers()['content-type']).toMatch(/javascript/)
  await page.goto('/')
  await expect(page.locator('#catalogo .nft-card')).toHaveCount(9)
  const image = await page.locator('#catalogo .nft-card img').first().getAttribute('src')
  const asset = await request.get(image!)
  expect(asset.status()).toBe(200)
  expect(asset.headers()['content-type']).toMatch(/^image\//)
  await page.goto('/nft/emerald-ape-042')
  await expect(page.locator('.nft-price-row')).toContainText('1.19')
  await page.reload()
  await expect(page.locator('.nft-price-row')).toContainText('1.19')
  await page.goto('/checkout')
  await expect(page).toHaveURL(/\/login\?/)
  await expect(page.getByRole('button', { name: 'Entrar ou criar conta' })).toBeVisible()
})

test('compra publicada preserva carrinho, autentica e confirma pelo backend simulado', async ({ page }) => {
  await page.goto('/nft/emerald-ape-042')
  await page.getByRole('button', { name: /^(COMPRAR|Comprar NFT)$/ }).click()
  await expect(page.locator('.cart-item')).toHaveCount(1)
  await page.reload()
  await expect(page.locator('.cart-item')).toHaveCount(1)
  await page.getByRole('link', { name: 'Continuar para pagamento' }).click()
  await page.getByRole('button', { name: 'Entrar ou criar conta' }).click()
  const auth = page.getByRole('dialog')
  await auth.locator('[name=email]').fill('colecionador@kurio.test')
  await auth.locator('[name=password]').fill('Kurio123!')
  await auth.locator('button.auth-submit').click()
  await expect(auth).toBeHidden()
  await expect(page.locator('.payment-wallet-option')).toHaveCount(2)
  await page.getByRole('radio', { name: 'MetaMask', exact: true }).check()
  let orders = 0
  page.on('request', (request) => { if (request.method() === 'POST' && new URL(request.url()).pathname === '/api/orders') orders++ })
  await page.getByRole('button', { name: 'Confirmar compra', exact: true }).click()
  const review = page.getByRole('dialog', { name: 'Revise sua compra' })
  await expect(review).toBeVisible()
  await review.getByRole('button', { name: 'Confirmar compra', exact: true }).click()
  await expect(page).toHaveURL(/\/orders\//)
  await expect(page.getByRole('dialog', { name: 'Seus NFTs agora estão na sua carteira' })).toBeVisible()
  expect(orders).toBe(1)
})
